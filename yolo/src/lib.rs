pub fn find_object_by_yolo(
    original_img: DynamicImage,
) -> Result<Vec<BoundingBox>, Box<dyn std::error::Error>> {
	let root = get_project_root();
    let (img_width, img_height) = (original_img.width(), original_img.height());
    let img = original_img.resize_exact(640, 640, FilterType::CatmullRom);
    let mut input = Array::zeros((1, 3, 640, 640));
    for pixel in img.pixels() {
        let x = pixel.0 as _;
        let y = pixel.1 as _;
        let [r, g, b, _] = pixel.2.0;
        input[[0, 0, y, x]] = (r as f32) / 255.;
        input[[0, 1, y, x]] = (g as f32) / 255.;
        input[[0, 2, y, x]] = (b as f32) / 255.;
    }

    let folder = std::env::var("FILES_FOLDER").unwrap_or_else(|_| "files".into());
	let path = root.join(folder).join("yolov8m.onnx");
    let mut model = Session::builder()?.commit_from_file(path)?;
    // Run YOLOv8 inference
    let outputs: SessionOutputs =
        model.run(inputs!["images" => TensorRef::from_array_view(&input)?])?;
    let output = outputs["output0"]
        .try_extract_array::<f32>()?
        .t()
        .into_owned();

    let mut boxes = Vec::new();
    let output = output.slice(s![.., .., 0]);
    for row in output.axis_iter(Axis(0)) {
        let row: Vec<_> = row.iter().copied().collect();

        let (class_id, prob) = row
            .iter()
            // skip bounding box coordinates
            .skip(4)
            .enumerate()
            .map(|(index, value)| (index, *value))
            .reduce(|accum, row| if row.1 > accum.1 { row } else { accum })
            .unwrap();

        //only human
        if prob < 0.5 || class_id != 0 {
            continue;
        }
        let label = YOLOV8_CLASS_LABELS[class_id];
        let xc = row[0] / 640. * (img_width as f32);
        let yc = row[1] / 640. * (img_height as f32);
        let w = row[2] / 640. * (img_width as f32);
        let h = row[3] / 640. * (img_height as f32);

        boxes.push((
            BoundingBox {
                x1: xc - w / 2.,
                y1: yc - h / 2.,
                x2: xc + w / 2.,
                y2: yc + h / 2.,
            },
            label,
            prob,
        ));
    }

    boxes.sort_by(|box1, box2| box2.2.total_cmp(&box1.2));
    let mut result = Vec::new();

    while !boxes.is_empty() {
        result.push(boxes[0]);
        boxes = boxes
            .iter()
            .filter(|box1| intersection(&boxes[0].0, &box1.0) / union(&boxes[0].0, &box1.0) < 0.7)
            .copied()
            .collect();
    }

    let mut bounding_boxes = Vec::new();

    for (bbox, _label, _confidence) in result {
        bounding_boxes.push(BoundingBox {
            x1: bbox.x1,
            y1: bbox.y1,
            x2: bbox.x2 - bbox.x1,
            y2: bbox.y2 - bbox.y1,
        });
    }

    Ok(bounding_boxes)
}
